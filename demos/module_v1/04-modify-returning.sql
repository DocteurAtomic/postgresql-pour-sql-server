-- Clip V1.4: UPDATE ... FROM, DELETE ... USING, RETURNING with OLD and NEW (18).
-- Lab database, psql. Works on a copy, outils.mv1_session, created here and dropped at the
-- end. One statement fails on purpose: ON_ERROR_STOP is off around it.
create table outils.mv1_session as
select sessionid, stageid, languecd, datedebut, prix from stage.session;
alter table outils.mv1_session add primary key (sessionid);
alter table outils.mv1_session
    alter column sessionid add generated by default as identity (start with 10000);

-- The T-SQL habit: the target table repeated in FROM, with an alias. Here it is a second
-- copy of the table, joined to nothing: every row of the target is updated.
begin;
update outils.mv1_session set prix = s.prix * 1.10
from outils.mv1_session s
join stage.stagelangue sl on sl.stageid = s.stageid and sl.languecd = s.languecd
where sl.titre = 'PostgreSQL 9 Optimisation';
rollback;

-- The alias goes on the target, the other tables in FROM, the join in WHERE.
-- A column of SET takes no alias.
\set ON_ERROR_STOP off
update outils.mv1_session s set s.prix = s.prix * 1.10 where s.sessionid = 2137;
\set ON_ERROR_STOP on
update outils.mv1_session s
set prix = s.prix * 1.10
from stage.stagelangue sl
where sl.stageid = s.stageid and sl.languecd = s.languecd
  and sl.titre = 'PostgreSQL 9 Optimisation'
  and s.datedebut >= date '2020-01-01'
returning s.sessionid, old.prix as old_price, new.prix as new_price;

-- DELETE ... USING: the sessions of course 24 planned after its cancellation date.
-- RETURNING gives the deleted rows, and the columns of the USING tables.
delete from outils.mv1_session s
using stage.stage st
where st.stageid = s.stageid and st.stageid = 24 and s.datedebut > st.dateannulation
returning s.sessionid, s.datedebut, st.dateannulation;

-- INSERT ... RETURNING the generated key, instead of SCOPE_IDENTITY() or OUTPUT inserted.
insert into outils.mv1_session (stageid, languecd, datedebut, prix)
values (119, 'FR', date '2026-11-16', 3900)
returning sessionid, new.datedebut, old.datedebut is null as no_old_row;

drop table outils.mv1_session;
