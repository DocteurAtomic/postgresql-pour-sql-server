-- Clip 4.6: identity, sequences, UUID. Lab database, psql, after 00-setup.sql (pgstattuple).
-- Two statements fail on purpose: ON_ERROR_STOP is off around them.

-- GENERATED ALWAYS refuses an explicit value, unless OVERRIDING SYSTEM VALUE.
create table outils.m04_ident (id integer generated always as identity primary key, label text);
insert into outils.m04_ident (label) values ('first'), ('second');
\set ON_ERROR_STOP off
insert into outils.m04_ident (id, label) values (10, 'explicit');
\set ON_ERROR_STOP on
insert into outils.m04_ident (id, label) overriding system value values (10, 'explicit');

-- GENERATED BY DEFAULT accepts it, and the sequence does not know.
alter table outils.m04_ident alter column id set generated by default;
insert into outils.m04_ident (id, label) values (3, 'by default');
\set ON_ERROR_STOP off
insert into outils.m04_ident (label) values ('next');
\set ON_ERROR_STOP on

-- The sequence behind the column, and the gap a rollback leaves.
select pg_get_serial_sequence('outils.m04_ident', 'id') as sequence;
begin;
insert into outils.m04_ident (label) values ('rolled back') returning id;
rollback;
insert into outils.m04_ident (label) values ('after rollback') returning id;
select id, label from outils.m04_ident order by id;

-- setval puts the sequence after the largest value.
select setval(pg_get_serial_sequence('outils.m04_ident', 'id'), max(id)) from outils.m04_ident;
insert into outils.m04_ident (label) values ('after setval') returning id;
drop table outils.m04_ident;

-- serial, the older form: a sequence and a default.
create table outils.m04_serial (id serial primary key, label text);
\d outils.m04_serial
drop table outils.m04_serial;

-- The port: identities, and sequences already past the largest value.
select last_value, (select max(sessionid) from stage.session) as max_sessionid
from stage.session_sessionid_seq;

-- UUID: random (version 4) or ordered by time (version 7, new in PostgreSQL 18).
select gen_random_uuid() as v4, uuidv7() as v7;
select uuid_extract_version(u) as version, uuid_extract_timestamp(u) is not null as has_timestamp
from (select uuidv7() as u) as t;

-- 200,000 rows in each table, then the size and fill of each primary key.
create table outils.m04_uuid_v4 (id uuid primary key default gen_random_uuid(), n integer);
create table outils.m04_uuid_v7 (id uuid primary key default uuidv7(), n integer);
insert into outils.m04_uuid_v4 (n) select g from generate_series(1, 200000) as g;
insert into outils.m04_uuid_v7 (n) select g from generate_series(1, 200000) as g;
select 'v4' as uuid, leaf_pages, round(avg_leaf_density) as leaf_fill_pct,
       pg_size_pretty(pg_relation_size('outils.m04_uuid_v4_pkey')) as size
from pgstatindex('outils.m04_uuid_v4_pkey')
union all
select 'v7', leaf_pages, round(avg_leaf_density),
       pg_size_pretty(pg_relation_size('outils.m04_uuid_v7_pkey'))
from pgstatindex('outils.m04_uuid_v7_pkey');
drop table outils.m04_uuid_v4;
drop table outils.m04_uuid_v7;
