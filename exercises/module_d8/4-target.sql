-- Module D8 exercise, solution: stage.session in PostgreSQL (pgd8-expg, database pachadata).
-- Types as close as possible to SQL Server's; bit becomes boolean, tinyint smallint. The
-- foreign keys wait for the tables they reference, which this exercise does not migrate.
create schema stage;
create table stage.session (
    sessionid        integer generated by default as identity
                     constraint pk_sessionstage primary key,
    stageid          integer not null,
    languecd         char(2) not null,
    salleformationid integer,
    datedebut        date not null,
    prix             numeric(8,2),
    note             smallint,
    statut           char(10),
    datecreation     date not null default current_date,
    duree            smallint,
    intraentrerprise boolean not null default false,
    remarques        varchar(1500),
    formateurid      integer
);
